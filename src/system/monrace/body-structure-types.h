/*!
 * @brief モンスターの体構造列挙
 * @details 装備可能スロットを体構造単位で決定するための分類。
 *          HUMANOID をデフォルトとし、全装備スロット可能。
 *          詳細は docs/monster-body-structure-equipment-slots.md 参照。
 */
#pragma once

#include <cstdint>

enum class BodyStructureType : uint8_t {
    HUMANOID = 0, //!< 二足歩行・両手・頭・胴体: 全装備スロット有効 (デフォルト)
    BIPEDAL = 1, //!< 二足型 (恐竜型・翼手型): 前肢が翼/鉤爪で武器装備不可、首/光源/胴体/頭/脚のみ
    QUADRUPED = 2, //!< 四足獣: 首/胴体/頭のみ
    SERPENTINE = 3, //!< 蛇型 (WORM 分離後は多足類の暫定置き場): 首と胴体のみ
    AMORPHOUS = 4, //!< 粘体型 (スライム・ジェル): リングのみ (擬足にはめる)
    INCORPOREAL = 5, //!< 幽霊・ベクター: 装備一切不可
    DRACONIC = 6, //!< ドラゴン: HUMANOID 装備可能 + 拡張スロット (尾の指輪)
    FORMLESS = 7, //!< 不定形: 決まった形を持たない塊・雲・霧。装備枠一切なし
    GASEOUS = 8, //!< 気体: 毒ガス・煙・蒸気。実体が希薄で装備枠一切なし
    VORTEX = 9, //!< ボルテックス: 渦・竜巻・奔流。回転する現象そのもので装備枠一切なし
    XAREN = 10, //!< ザレン型: 岩を泳ぐ多腕多脚の異形。手足の形が人型と異なり装備枠一切なし
    AVIAN = 11, //!< 鳥型: 前肢が完全な翼。首/胴体/頭/脚 + 拡張 (両翼の装飾)。光源も持てない
    WORM = 12, //!< 長胴型 (ミミズ〜蛇〜東洋竜): 手足を持たない長い胴。首/胴体 + 拡張 (尾の指輪)
    INSECTOID = 13, //!< 節足型 (昆虫・蛛形・多足・甲殻): 外骨格と多数の脚。首/胴体/頭のみ
    WINGED_HUMANOID = 14, //!< 有翼人 (有翼のデーモン・天使等): HUMANOID から体の上 (クローク) を除いた全スロット + 拡張 (両翼の装飾)
    WING_ARMED_HUMANOID = 15, //!< 翼腕人 (ハーピー・鴉人等): 両腕が翼なので利き手・逆手が無い。体の上は羽織れる + 拡張 (両翼の装飾)
    SPHERE = 16, //!< 球体: 手足も頭も無い球そのもの。装備枠一切なし
    MAX,
};
